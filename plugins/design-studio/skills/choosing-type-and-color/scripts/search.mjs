#!/usr/bin/env node
// Search the curated palette and font-pairing datasets, and export a tokens CSS file.
// Usage:
//   node search.mjs palettes [--tags a,b] [--mood x] [--industry y] [--text q] [--mode light|dark] [--json]
//   node search.mjs fonts    [--tags a,b] [--mood x] [--industry y] [--text q] [--json]
//   node search.mjs export <palette-id> [--font <font-id>] [--mode light|dark] [--dark] [--out tokens.css]
//   node search.mjs contrast <hex> <hex>
// No dependencies. Data lives in ../references/*.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const DATA_DIR = resolve(here, '..', 'references')

export function loadData(dir = DATA_DIR) {
  const read = (f) => JSON.parse(readFileSync(resolve(dir, f), 'utf8'))
  return { palettes: read('palettes.json'), fonts: read('font-pairings.json') }
}

// WCAG 2.x relative luminance and contrast ratio for #RRGGBB values.
export function luminance(hex) {
  const c = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}
export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return Math.round(((hi + 0.05) / (lo + 0.05)) * 100) / 100
}

const norm = (s) => String(s).trim().toLowerCase()
const csv = (s) => (s ? String(s).split(',').map(norm).filter(Boolean) : [])

// A query matches when every given facet matches. Within a facet, any listed value may match.
export function filterEntries(entries, q = {}) {
  const tags = csv(q.tags), moods = csv(q.mood), inds = csv(q.industry), text = q.text ? norm(q.text) : ''
  const scored = []
  for (const e of entries) {
    const mood = e.mood.map(norm), ind = e.industries.map(norm), use = e.use.map(norm)
    if (moods.length && !moods.some((m) => mood.includes(m))) continue
    if (inds.length && !inds.some((i) => ind.includes(i))) continue
    if (tags.length && !tags.every((t) => use.includes(t) || mood.includes(t) || ind.includes(t))) continue
    if (q.mode && e.modes && !e.modes.includes(q.mode)) continue
    const hay = [e.id, e.name, e.notes, ...mood, ...ind, ...use].join(' ').toLowerCase()
    if (text && !text.split(/\s+/).every((w) => hay.includes(w))) continue
    let score = 0
    for (const m of moods) if (mood.includes(m)) score += 2
    for (const i of inds) if (ind.includes(i)) score += 3
    for (const t of tags) score += 1
    if (text) score += 1
    scored.push({ e, score })
  }
  return scored.sort((a, b) => b.score - a.score || a.e.id.localeCompare(b.e.id)).map((s) => s.e)
}

export function formatPalette(p) {
  const c = p.contrast
  return [
    `${p.id}  (${p.name})  modes: ${p.modes.join(', ')}`,
    `  mood: ${p.mood.join(', ')} | industries: ${p.industries.join(', ')} | use: ${p.use.join(', ')}`,
    `  bg ${p.light.bg}  surface ${p.light.surface}  fg ${p.light.fg}  primary ${p.light.primary}  accent ${p.light.accent}`,
    `  contrast: text ${c.fgOnBg}:1, muted ${c.mutedOnBg}:1, button label ${c.onPrimaryOnPrimary}:1, accent on page ${c.accentOnBg}:1`,
    `  ${p.notes}`,
  ].join('\n')
}
export function formatFont(f) {
  return [
    `${f.id}  (${f.name})`,
    `  display: ${f.display.family} | body: ${f.body.family}${f.mono ? ` | mono: ${f.mono.family}` : ''}`,
    `  mood: ${f.mood.join(', ')} | industries: ${f.industries.join(', ')} | use: ${f.use.join(', ')}`,
    `  base ${f.scale.base}px, line-height ${f.scale.lh}, tracking ${f.scale.track}`,
    `  npm: ${f.fontsource.join(' ')}`,
    `  ${f.notes}`,
  ].join('\n')
}

const camel = (k) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
const COLOR_KEYS = ['bg', 'surface', 'fg', 'muted', 'border', 'primary', 'onPrimary', 'accent', 'success', 'warning', 'danger']

// Three layers: primitives (raw values), semantic aliases used by components, and a type/space/radius/motion scale.
export function renderTokensCss(palette, font, { withDark = false, mode = 'light' } = {}) {
  const set = palette[mode] || palette.light
  const lines = []
  lines.push(`/* Generated by choosing-type-and-color. Palette: ${palette.id}${font ? `, fonts: ${font.id}` : ''}. Edit freely; components use semantic names only. */`)
  if (font) lines.push(`/* Install fonts: npm i ${font.fontsource.join(' ')}  (or use ${font.googleFontsUrl}) */`)
  lines.push(':root {')
  lines.push('  /* Primitives */')
  for (const k of COLOR_KEYS) lines.push(`  --${'p-' + camel(k)}: ${set[k]};`)
  lines.push('')
  lines.push('  /* Semantic colours */')
  for (const k of COLOR_KEYS) lines.push(`  --color-${camel(k)}: var(--p-${camel(k)});`)
  lines.push('  --color-focus-ring: var(--p-primary);')
  lines.push('  --color-primary-hover: color-mix(in srgb, var(--p-primary) 88%, var(--p-fg));')
  lines.push('')
  lines.push(`  /* Chart series (each is at least 3:1 against the page background) */`)
  const series = palette.chart[mode] || palette.chart.light
  series.forEach((c, i) => lines.push(`  --chart-${i + 1}: ${c};`))
  lines.push('')
  lines.push('  /* Type */')
  if (font) {
    lines.push(`  --font-display: ${font.display.stack};`)
    lines.push(`  --font-body: ${font.body.stack};`)
    if (font.mono) lines.push(`  --font-mono: ${font.mono.stack};`)
    else lines.push('  --font-mono: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;')
  } else {
    lines.push('  --font-display: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;')
    lines.push('  --font-body: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;')
    lines.push('  --font-mono: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;')
  }
  const base = font ? font.scale.base : 16
  lines.push(`  --text-base: ${base / 16}rem;`)
  lines.push('  --text-sm: 0.875rem;')
  lines.push('  --text-lg: 1.125rem;')
  lines.push('  --text-xl: 1.75rem;')
  lines.push('  --text-display: clamp(2.25rem, 1.5rem + 3vw, 3.5rem);')
  lines.push(`  --leading-body: ${font ? font.scale.lh : 1.5};`)
  lines.push('  --leading-tight: 1.15;')
  lines.push('')
  lines.push('  /* Space (4px base) */')
  ;[1, 2, 3, 4, 6, 8, 12, 16].forEach((n) => lines.push(`  --space-${n}: ${n * 0.25}rem;`))
  lines.push('')
  lines.push('  /* Shape and depth */')
  lines.push('  --radius-sm: 4px;')
  lines.push('  --radius-md: 8px;')
  lines.push('  --radius-lg: 12px;')
  lines.push('  --shadow-sm: 0 1px 2px color-mix(in srgb, var(--p-fg) 8%, transparent);')
  lines.push('  --shadow-md: 0 4px 16px color-mix(in srgb, var(--p-fg) 10%, transparent);')
  lines.push('')
  lines.push('  /* Motion */')
  lines.push('  --duration-fast: 120ms;')
  lines.push('  --duration-base: 200ms;')
  lines.push('  --duration-slow: 360ms;')
  lines.push('  --ease-out: cubic-bezier(0.22, 1, 0.36, 1);')
  lines.push('}')
  if (withDark && palette.dark && mode === 'light') {
    lines.push('')
    lines.push('[data-theme="dark"] {')
    for (const k of COLOR_KEYS) lines.push(`  --${'p-' + camel(k)}: ${palette.dark[k]};`)
    palette.chart.dark.forEach((c, i) => lines.push(`  --chart-${i + 1}: ${c};`))
    lines.push('}')
  }
  lines.push('')
  lines.push('@media (prefers-reduced-motion: reduce) {')
  lines.push('  :root { --duration-fast: 0.01ms; --duration-base: 0.01ms; --duration-slow: 0.01ms; }')
  lines.push('}')
  return lines.join('\n') + '\n'
}

export function parseArgs(argv) {
  const out = { _: [] }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--json' || a === '--dark') out[a.slice(2)] = true
    else if (a.startsWith('--')) out[a.slice(2)] = argv[++i]
    else out._.push(a)
  }
  return out
}

export function run(argv, io = { out: console.log, err: console.error }, dir = DATA_DIR) {
  const args = parseArgs(argv)
  const [cmd, ...rest] = args._
  const { palettes, fonts } = loadData(dir)
  const q = { tags: args.tags, mood: args.mood, industry: args.industry, text: args.text, mode: args.mode }
  if (cmd === 'palettes' || cmd === 'fonts') {
    const res = filterEntries(cmd === 'palettes' ? palettes : fonts, cmd === 'fonts' ? { ...q, mode: undefined } : q)
    if (args.json) io.out(JSON.stringify(res, null, 2))
    else if (!res.length) io.out('No matches. Loosen a filter or list everything with no flags.')
    else io.out(res.map(cmd === 'palettes' ? formatPalette : formatFont).join('\n\n'))
    return 0
  }
  if (cmd === 'export') {
    const p = palettes.find((x) => x.id === rest[0])
    if (!p) { io.err(`Unknown palette "${rest[0] ?? ''}". Run: node search.mjs palettes`); return 1 }
    const f = args.font ? fonts.find((x) => x.id === args.font) : null
    if (args.font && !f) { io.err(`Unknown font pairing "${args.font}". Run: node search.mjs fonts`); return 1 }
    const mode = args.mode || 'light'
    if (!p.modes.includes(mode)) { io.err(`Palette ${p.id} has no ${mode} mode.`); return 1 }
    const css = renderTokensCss(p, f, { withDark: Boolean(args.dark), mode })
    if (args.out) {
      mkdirSync(dirname(resolve(args.out)), { recursive: true })
      writeFileSync(args.out, css)
      io.out(`Wrote ${args.out}`)
    } else io.out(css)
    return 0
  }
  if (cmd === 'contrast') {
    const [a, b] = rest
    if (!/^#[0-9a-fA-F]{6}$/.test(a || '') || !/^#[0-9a-fA-F]{6}$/.test(b || '')) { io.err('Usage: node search.mjs contrast #RRGGBB #RRGGBB'); return 1 }
    const r = contrast(a, b)
    io.out(`${r}:1  body text ${r >= 4.5 ? 'pass' : 'fail'}, large text ${r >= 3 ? 'pass' : 'fail'}`)
    return 0
  }
  io.err('Usage: node search.mjs palettes|fonts [--tags a,b] [--mood x] [--industry y] [--text q] [--json]\n       node search.mjs export <palette-id> [--font <id>] [--mode light|dark] [--dark] [--out tokens.css]\n       node search.mjs contrast #RRGGBB #RRGGBB')
  return 1
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = run(process.argv.slice(2))
}
